window.translateAppText = (text) => {
  if (!text) return text;
  if (document.documentElement.lang !== "te") return text === "None" ? "Healthy" : text;
  if (text.startsWith("Invalid image:")) {
    return `${teluguTranslations["Invalid image"]}: ${text.slice("Invalid image:".length).trim()}`;
  }
  if (text.startsWith("Prediction failed:")) {
    return `${teluguTranslations["Prediction failed."]} ${text.slice("Prediction failed:".length).trim()}`;
  }
  return teluguTranslations[text] || text;
};

window.translateAdviceText = (text) => {
  if (!text || document.documentElement.lang !== "te") return text;
  const normalized = String(text).trim();
  if (teluguTranslations[normalized]) return teluguTranslations[normalized];
  return normalized;
};

function setAppLanguage(language) {
  const selectedLanguage = language === "te" ? "te" : "en";
  document.documentElement.lang = selectedLanguage;
  localStorage.setItem("smartCauliflowerLanguage", selectedLanguage);
  const isAnalyzePage = window.location.pathname === "/analyze";
  document.title = selectedLanguage === "te"
    ? (isAnalyzePage ? "వ్యాధి మరియు నాణ్యత అంచనా | CauliVision" : "CauliVision | AICW")
    : (isAnalyzePage ? "Disease Prediction and Quality Prediction | CauliVision" : "CauliVision | AICW");
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = window.translateAppText(element.dataset.i18n);
  });
  document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
    element.alt = window.translateAppText(element.dataset.i18nAlt);
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = window.translateAppText(element.dataset.i18nPlaceholder);
  });
  document.querySelectorAll(".language-select").forEach((select) => {
    select.value = selectedLanguage;
  });
  window.dispatchEvent(new Event("app-language-change"));
}

document.querySelectorAll(".language-select").forEach((select) => {
  select.addEventListener("change", () => setAppLanguage(select.value));
});
setAppLanguage(localStorage.getItem("smartCauliflowerLanguage") || "en");
